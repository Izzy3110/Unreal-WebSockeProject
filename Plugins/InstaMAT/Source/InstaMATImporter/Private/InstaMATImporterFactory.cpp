InstaMAT::ArithmeticGraphValue FInstaMATImporterUtility::GetArithmeticValueForInput(UInstaMATInputBase* const Input)
{
	check(Input != nullptr);

	InstaMAT::ArithmeticGraphValue Value;
	FMemory::Memzero(Value);

	if (Input->IsA<UInstaMATInputBoolean>())
	{
		Value.BooleanValue = Cast<UInstaMATInputBoolean>(Input)->Value;
	}
	else if (Input->IsA<UInstaMATInputFloat32>())
	{
		Value.Float32Value = Cast<UInstaMATInputFloat32>(Input)->Value;
	}
	else if (Input->IsA<UInstaMATInputVector2F>())
	{
		UInstaMATInputVector2F* const Vector = Cast<UInstaMATInputVector2F>(Input);
		Value.Vector2FValue[0] = Vector->Value.X;
		Value.Vector2FValue[1] = Vector->Value.Y;
	}
	else if (Input->IsA<UInstaMATInputVector3F>())
	{
		UInstaMATInputVector3F* const Vector = Cast<UInstaMATInputVector3F>(Input);
		Value.Vector3FValue[0] = Vector->Value.X;
		Value.Vector3FValue[1] = Vector->Value.Y;
		Value.Vector3FValue[2] = Vector->Value.Z;
	}
	else if (Input->IsA<UInstaMATInputVector4F>())
	{
		UInstaMATInputVector4F* const Vector = Cast<UInstaMATInputVector4F>(Input);
		Value.Vector4FValue[0] = Vector->Value.X;
		Value.Vector4FValue[1] = Vector->Value.Y;
		Value.Vector4FValue[2] = Vector->Value.Z;
		Value.Vector4FValue[3] = Vector->Value.W;
	}
	else if (Input->IsA<UInstaMATInputInt32>())
	{
		Value.Int32Value = Cast<UInstaMATInputInt32>(Input)->Value;
	}
	else if (Input->IsA<UInstaMATInputVector2I32>())
	{
		UInstaMATInputVector2I32* const Vector = Cast<UInstaMATInputVector2I32>(Input);
		Value.Vector2I32Value[0] = Vector->Value.X;
		Value.Vector2I32Value[1] = Vector->Value.Y;
	}
	else if (Input->IsA<UInstaMATInputVector3I32>())
	{
		UInstaMATInputVector3I32* const Vector = Cast<UInstaMATInputVector3I32>(Input);
		Value.Vector3I32Value[0] = Vector->Value.X;
		Value.Vector3I32Value[1] = Vector->Value.Y;
		Value.Vector3I32Value[2] = Vector->Value.Z;
	}
	else if (Input->IsA<UInstaMATInputVector4I32>())
	{
		UInstaMATInputVector4I32* const Vector = Cast<UInstaMATInputVector4I32>(Input);
		Value.Vector4I32Value[0] = Vector->Value[0];
		Value.Vector4I32Value[1] = Vector->Value[1];
		Value.Vector4I32Value[2] = Vector->Value[2];
		Value.Vector4I32Value[3] = Vector->Value[3];
	}
	else if (Input->IsA<UInstaMATInputMatrix2F>())
	{
		UInstaMATInputMatrix2F* const Vector = Cast<UInstaMATInputMatrix2F>(Input);
		Value.Vector4FValue[0] = Vector->Value.X;
		Value.Vector4FValue[1] = Vector->Value.Y;
		Value.Vector4FValue[2] = Vector->Value.Z;
		Value.Vector4FValue[3] = Vector->Value.W;
	}
	else if (Input->IsA<UInstaMATInputMatrix3F>())
	{
		FMemory::Memcpy(&Value, &Cast<UInstaMATInputMatrix3F>(Input)->Value, sizeof(float) * UInstaMATInputMatrix3F::VectorSize);
	}
	else if (Input->IsA<UInstaMATInputMatrix4F>())
	{
		FMemory::Memcpy(&Value, &Cast<UInstaMATInputMatrix4F>(Input)->Value, sizeof(float) * UInstaMATInputMatrix4F::VectorSize);
	}

	return Value;
}

