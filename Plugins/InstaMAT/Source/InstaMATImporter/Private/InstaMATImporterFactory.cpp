const InstaMAT::IGraph* FInstaMATImporterUtility::GetGraphClassFromGraphObject(InstaMAT::IInstaMAT* InstaMAT, const InstaMAT::IGraphObject* const GraphObject)
{
	check(InstaMAT != nullptr);
	check(GraphObject != nullptr);

	const InstaMAT::IGraph* const Graph = GraphObject->AsGraph();

	if (Graph == nullptr)
	{
		if (const InstaMAT::IGraphTemplate* const Template = GraphObject->AsTemplate())
		{
			// try getting the the graph from the graph class
			ANSICHAR Buffer[256u];
			if (Template->GetClassID(Buffer, sizeof(Buffer)) > 0u)
			{
				if (const InstaMAT::IGraphObject* const GraphClassObject = InstaMAT->GetGraphObjectByID(Buffer))
					return GraphClassObject->AsGraph();
			}
		}
	}

	return Graph;
}

void FInstaMATImporterUtility::ImportInputParametersForGraphObject(UInstaMATImporterGraphInstance* const GraphInstance, const InstaMAT::IGraphObject* const GraphObject, FInstaMATModule& InstaMATModule)
{
	if (GraphInstance == nullptr || GraphObject == nullptr)
		return;

	InstaMAT::IInstaMAT* const InstaMATAPI = InstaMATModule.GetInstaMATAPI();
	check(InstaMATAPI != nullptr);

	const InstaMAT::IGraph* Graph = GetGraphClassFromGraphObject(InstaMATAPI, GraphObject);

	if (Graph == nullptr)
	{
		UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not retrieve Graph for Graph Object with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/ true)));
		return;
	}

	const uint32 InputParameterCount = Graph->GetParameterCount(InstaMAT::IGraph::ParameterTypeInput);
	InstaMAT::IElementExecution* Execution = nullptr;

	// In order to get the correct variable values for templates, we need to get the instance through an execution
	if (const InstaMAT::IGraphTemplate* const Template = GraphObject->AsTemplate())
	{
		Execution = InstaMATAPI->AllocElementExecution();
		if (Execution == nullptr)
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not create InstaMAT Execution"));
			return;
		}
		if (!Execution->CreateInstance(*Template, InstaMAT::ElementExecutionFlags::None))
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not create Instance from InstaMAT Execution"));
			InstaMATModule.GetInstaMATInterface()->DeallocElementExecutionOnTaskThread(Execution);
			return;
		}
		Graph = Execution->GetInstance();
	}

	if (Graph == nullptr)
	{
		UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not retrieve parameter settings"));
		return;
	}

	for (uint32 InputParameterIndex = 0u; InputParameterIndex < InputParameterCount; InputParameterIndex++)
	{
		const InstaMAT::IGraphVariable* const GraphVariable = Graph->GetParameterAtIndex(InputParameterIndex, InstaMAT::IGraph::ParameterTypeInput);

		if (GraphVariable->IsAuxiliary())
			continue;

		const InstaMAT::IGraphObject* const GraphVariableObject = GraphVariable->AsObject();
		const InstaMAT::IGraphVariable::Type VariableType = GraphVariable->GetVariableTypeValue();
		const ANSICHAR* const FriendlyName = GraphVariableObject->GetName(/*friendlyName:*/true);
		const FString InputName(UTF8_TO_TCHAR(FriendlyName));

		// Ignore scene input parameters
		if (VariableType == InstaMAT::IGraphVariable::TypeElementScene)
			continue;

		UInstaMATInputBase* const InputParameter = FInstaMATImporterUtility::CreateInputObjectForType(GraphInstance, VariableType, InputName);
		check(InputParameter != nullptr);

		// set initial visibility
		InputParameter->bIsVisible = Graph->IsParameterUIRelevant(*GraphVariable, /*hideAdvanced:*/ true);

		FString Category = FString();

		if (GraphVariableObject->ContainsMetaDataKeyChar(InstaMAT::MetaData::KeyCategory))
		{
			if (const ANSICHAR* const CategoryFromObject = GraphVariableObject->GetMetaDataAsChar(InstaMAT::MetaData::KeyCategory))
			{
				Category = FString(UTF8_TO_TCHAR(CategoryFromObject));
			}
		}

		FString ToolTip = FString();

		if (GraphVariableObject->ContainsMetaDataKeyChar(InstaMAT::MetaData::KeyDocumentation))
		{
			if (const ANSICHAR* const Documentation = GraphVariableObject->GetMetaDataAsChar(InstaMAT::MetaData::KeyDocumentation))
			{
				ToolTip = FString(UTF8_TO_TCHAR(Documentation));
			}
		}

		ApplyMetaDataForInputWithGraphVariable(InputParameter, GraphVariableObject);

		// NOTE: enum needs a custom UI and also needs to collect the enum values in a separate fashion
		if (InputParameter->IsA<UInstaMATInputEnumValue>())
		{
			const uint32 EnumValue = GraphVariable->GetEnumValueUI32();
			uint32 EnumCaseCount = GraphVariable->GetEnumCaseCount();
			UInstaMATInputEnumValue* const EnumParameter = Cast<UInstaMATInputEnumValue>(InputParameter);

			if (EnumCaseCount == ~0u || EnumValue == ~0u)
			{
				UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not retrieve Enum Values for Graph with name='%s'"), ANSI_TO_TCHAR(FriendlyName));
				EnumCaseCount = 0u;
			}

			for (uint32 EnumIndex = 0u; EnumIndex < EnumCaseCount; EnumIndex++)
			{
				const ANSICHAR* const EnumStringValue = GraphVariable->GetEnumValueString(EnumIndex);

				if (EnumStringValue == nullptr)
				{
					UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not retrieve Enum Value String for Graph with name='%s'"), ANSI_TO_TCHAR(FriendlyName));
					break;
				}

				// NOTE: Shared pointers can't be used for properties.
				EnumParameter->EnumValues.Add(FString(UTF8_TO_TCHAR(EnumStringValue)));
				EnumParameter->EnumStringValues.Add(MakeShareable<FString>(new FString(UTF8_TO_TCHAR(EnumStringValue))));
			}
			EnumParameter->DefaultValue = EnumValue;
			EnumParameter->Value = EnumValue;
		}
		else if (InputParameter->IsA<UInstaMATInputElementString>())
		{
			UInstaMATInputElementString* const StringParameter = Cast<UInstaMATInputElementString>(InputParameter);
			StringParameter->DefaultValue = FString(UTF8_TO_TCHAR(GraphVariable->GetElementStringValue()));
			StringParameter->Value = StringParameter->DefaultValue;
		}
		else if (IsInstaMATInputClassArithmetic(InputParameter->GetClass()) || InputParameter->IsA<UInstaMATInputElementImage>() || InputParameter->IsA<UInstaMATInputElementImageGrayscale>())
		{
			InstaMAT::ArithmeticGraphValue ArithmeticValue = GraphVariable->GetArithmeticValue();

			// ensure percentage sliders have percentage values
			if (InputParameter->ControlType == InstaMAT::IGraphVariable::UIControlTypePercentageSlider)
			{
				for (uint32 Index = 0u; Index < 16u; Index++)
				{
					ArithmeticValue.Matrix4FValue[Index] *= 100.0f;
				}
			}

			SetArithmeticValueForInput(ArithmeticValue, InputParameter);
		}

		InputParameter->InputName = InputName;
		InputParameter->Index = InputParameterIndex;
		InputParameter->ParentGraphID = GraphInstance->GraphID;
		InputParameter->Parent = GraphInstance;
		InputParameter->Category = Category;
		InputParameter->ToolTip = ToolTip;

		GraphInstance->InputParameters.Add(InputParameter);
	}

	if (Execution != nullptr)
	{
		InstaMATModule.GetInstaMATInterface()->DeallocElementExecutionOnTaskThread(Execution);
	}
}

void FInstaMATImporterUtility::ImportOutputParametersForGraphObject(UInstaMATImporterGraphInstance* const GraphInstance, const InstaMAT::IGraphObject* const GraphObject, FInstaMATModule& InstaMATModule, UPackage* const UnrealPackage)
{
	if (GraphInstance == nullptr || GraphObject == nullptr || UnrealPackage == nullptr)
		return;

	const InstaMAT::IGraph* const Graph = GetGraphClassFromGraphObject(InstaMATModule.GetInstaMATAPI(), GraphObject);

	if (Graph == nullptr)
	{
		UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not retrieve Graph for Graph Object with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/ true)));
		return;
	}

	const uint32 OutputParameterCount = Graph->GetParameterCount(InstaMAT::IGraph::ParameterTypeOutput);

	// NOTE: as we want to create a texture we need an Unreal Package to save the asset in
	UnrealPackage->FullyLoad();
	TSet<FName> UsedNames;

	/**
	 * Object for storing names of an output.
	 */
	struct FNamePair
	{
		FNamePair(FString&& InOutputName, FName&& InObjectName) :
		OutputName(InOutputName),
		ObjectName(InObjectName)
		{
		}

		FString OutputName;	/**< The Output name. */
		FName ObjectName;	/**< The UObject name. */
	};

	/// The fnCreateValidOutputObjectName lambda creates valid names for output objects.
	const auto fnCreateValidOutputObjectName = [&UsedNames](const FString& InstanceName, const FString& OutputName, const FString& TypeName) -> FNamePair
	{
		FString ObjectName = FInstaMATImporterUtility::EnsureValidObjectName(OutputName);
		FName UsedName = FName(FString::Format(TEXT("{0}_{1}"), { InstanceName, OutputName }));

		uint32 ExistingNameCount = 1u;

		while (UsedNames.Contains(UsedName))
		{
			ObjectName = FString::Format(TEXT("{0}_{1}_{2}_{3}"), { InstanceName, OutputName, ExistingNameCount, TypeName });
			UsedName = FName(FString::Format(TEXT("{0}_{1}_{2}"), { InstanceName, OutputName, ExistingNameCount }));
		}
		UsedNames.Emplace(UsedName);

		return FNamePair(MoveTemp(ObjectName), MoveTemp(UsedName));
	};

	static const TArray<FString> kBaseColorNames = { TEXT("albedo"), TEXT("basecolor"), TEXT("diffuse"), TEXT("base color"), TEXT("base_color")};

	// output texture parameters
	for (uint32 OutputParameterIndex = 0u; OutputParameterIndex < OutputParameterCount; OutputParameterIndex++)
	{
		const InstaMAT::IGraphVariable* const GraphVariable = Graph->GetParameterAtIndex(OutputParameterIndex, InstaMAT::IGraph::ParameterTypeOutput);
		const InstaMAT::IGraphVariable::Type VariableType = GraphVariable->GetVariableTypeValue();

		if (VariableType != InstaMAT::IGraphVariable::TypeElementImage &&
			VariableType != InstaMAT::IGraphVariable::TypeElementImageGray &&
			VariableType != InstaMAT::IGraphVariable::TypeAtomOutputImage &&
			VariableType != InstaMAT::IGraphVariable::TypeAtomOutputImageGray)
			continue;

		const InstaMAT::IGraphObject* const GraphVariableObject = GraphVariable->AsObject();
		const ANSICHAR* const FriendlyName = GraphVariableObject->GetName(/*friendlyName:*/ true);

		check(FriendlyName != nullptr);

		const FString OutputName(FInstaMATImporterUtility::EnsureValidObjectName(FString(UTF8_TO_TCHAR(FriendlyName))));
		const FNamePair NamePair = fnCreateValidOutputObjectName(GraphInstance->CustomName, OutputName, TEXT("Texture"));
		const FString OutputNameLower = OutputName.ToLower();

		if (VariableType == InstaMAT::IGraphVariable::TypeElementImageGray ||
			VariableType == InstaMAT::IGraphVariable::TypeAtomOutputImageGray)
		{
			if (kBaseColorNames.ContainsByPredicate([&OutputNameLower](const FString& Value) { return Value == OutputNameLower; }))
			{
				GraphInstance->bIsBaseColorGrayscale = true;
			}
		}

		UInstaMATOutput* const OutputParameter = NewObject<UInstaMATOutput>(GraphInstance, NamePair.ObjectName);
		OutputParameter->OutputName = NamePair.OutputName;
		OutputParameter->ParentGraphID = GraphInstance->GraphID;
		OutputParameter->Index = OutputParameterIndex;
		OutputParameter->Brush = nullptr;
		OutputParameter->ColorChannelCount = (VariableType == InstaMAT::IGraphVariable::TypeElementImage || VariableType == InstaMAT::IGraphVariable::TypeAtomOutputImage) ? 4u : 1u;
		GraphInstance->OutputParameters.Add(OutputParameter);
	}

	// mesh output parameters
	for (uint32 OutputParameterIndex = 0u; OutputParameterIndex < OutputParameterCount; OutputParameterIndex++)
	{
		const InstaMAT::IGraphVariable* const GraphVariable = Graph->GetParameterAtIndex(OutputParameterIndex, InstaMAT::IGraph::ParameterTypeOutput);

		if (GraphVariable->GetVariableTypeValue() != InstaMAT::IGraphVariable::TypeElementMesh)
			continue;

		const InstaMAT::IGraphObject* const GraphVariableObject = GraphVariable->AsObject();
		const ANSICHAR* const FriendlyName = GraphVariableObject->GetName(/*friendlyName:*/ true);

		check(FriendlyName != nullptr);

		const FString OutputName(FInstaMATImporterUtility::EnsureValidObjectName(FString(UTF8_TO_TCHAR(FriendlyName))));
		const FNamePair NamePair = fnCreateValidOutputObjectName(GraphInstance->CustomName, OutputName, TEXT("Mesh"));

		UInstaMATMeshOutput* const OutputParameter = NewObject<UInstaMATMeshOutput>(GraphInstance, NamePair.ObjectName);
		OutputParameter->OutputName = NamePair.OutputName;
		OutputParameter->ParentGraphID = GraphInstance->GraphID;
		OutputParameter->Index = OutputParameterIndex;
		OutputParameter->Brush = nullptr;
		GraphInstance->OutputMeshParameters.Add(OutputParameter);
	}

	// scene graph output parameters
	for (uint32 OutputParameterIndex = 0u; OutputParameterIndex < OutputParameterCount; OutputParameterIndex++)
	{
		const InstaMAT::IGraphVariable* const GraphVariable = Graph->GetParameterAtIndex(OutputParameterIndex, InstaMAT::IGraph::ParameterTypeOutput);

		if (GraphVariable->GetVariableTypeValue() != InstaMAT::IGraphVariable::TypeElementScene)
			continue;

		const InstaMAT::IGraphObject* const GraphVariableObject = GraphVariable->AsObject();
		const ANSICHAR* const FriendlyName = GraphVariableObject->GetName(/*friendlyName:*/ true);

		check(FriendlyName != nullptr);

		const FString OutputName(FInstaMATImporterUtility::EnsureValidObjectName(FString(UTF8_TO_TCHAR(FriendlyName))));
		const FNamePair NamePair = fnCreateValidOutputObjectName(GraphInstance->CustomName, OutputName, TEXT("Scene"));

		UInstaMATGraphSceneOutput* const OutputParameter = NewObject<UInstaMATGraphSceneOutput>(GraphInstance, NamePair.ObjectName);
		OutputParameter->OutputName = NamePair.OutputName;
		OutputParameter->ParentGraphID = GraphInstance->GraphID;
		OutputParameter->Index = OutputParameterIndex;
		OutputParameter->Root = nullptr;
		GraphInstance->OutputSceneParameters.Add(OutputParameter);
	}
}

void FInstaMATImporterUtility::ImportOutputDataForGraphObject(UInstaMATImporterGraphInstance* const GraphInstance, const InstaMAT::IGraphObject* const GraphObject, FInstaMATModule& InstaMATModule, UPackage* const UnrealPackage)
{
	IInstaMAT* const InstaMATInterface = InstaMATModule.GetInstaMATInterface();
	check(InstaMATInterface != nullptr);

	const FString ExecutionKey = GraphInstance->UUID.ToString();
	const FString GraphID = GraphInstance->GraphID;
	const TTuple<EInstaMATTextureSize, EInstaMATTextureSize> ResolutionDefaultSettings = InstaMATInterface->GetDefaultResolutionSettings();

	GraphInstance->ResolutionWidth = ResolutionDefaultSettings.Key;
	GraphInstance->ResolutionHeight = ResolutionDefaultSettings.Value;
	GraphInstance->ExecutionFormat = InstaMATInterface->GetDefaultExecutionFormatSettings();
	GraphInstance->SetDirty(/*bIsDirty:*/false, /*bNextPropertyEventIgnore:*/true); // Avoid updating 

	const uint32 TextureWidth = InstaMATImageUtility::TextureResolutionEnumToUInt32(GraphInstance->ResolutionWidth);
	const uint32 TextureHeight = InstaMATImageUtility::TextureResolutionEnumToUInt32(GraphInstance->ResolutionHeight);

	int ShiftWidth = 0;
	int ShiftHeight = 0;

	const InstaMAT::IGraph* const Graph = GetGraphClassFromGraphObject(InstaMATModule.GetInstaMATAPI(), GraphObject);

	if (Graph == nullptr)
	{
		UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not retrieve Graph for Graph Object with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/ true)));
		return;
	}

	// execute and read output textures
	if (const InstaMAT::IGraphTemplate* const Template = GraphObject->AsTemplate())
	{
		if (!InstaMATInterface->AllocElementExecutionFromTemplate(ExecutionKey, *Template, GraphInstance->bIsGrayScalePermutation ? InstaMAT::ElementExecutionFlags::GrayscalePermutation : InstaMAT::ElementExecutionFlags::None))
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not allocate ElementExecution for Template with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/true)));
			return;
		}
	}
	else
	{
		if (!InstaMATInterface->AllocElementExecution(ExecutionKey, GraphID, Graph, GraphInstance->bIsGrayScalePermutation ? InstaMAT::ElementExecutionFlags::GrayscalePermutation : InstaMAT::ElementExecutionFlags::None))
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not allocate ElementExecution for Graph with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/true)));
			return;
		}
	}
	const InstaMAT::ElementExecutionFormat::Type ExecutionFormat = (InstaMAT::ElementExecutionFormat::Type)GraphInstance->ExecutionFormat;

	if (!InstaMATInterface->SetElementExecutionFormat(ExecutionKey, TextureWidth, TextureHeight, ExecutionFormat))
	{
		InstaMATInterface->DeallocElementExecution(ExecutionKey);
		UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not set ElementExecution format for='%s'"), *GraphInstance->GraphFriendlyName);
		return;
	}

	if (!InstaMATInterface->SetCompositionGraphSettings(ExecutionKey, ExecutionFormat, InstaMAT::GetRotationInRadiansForInstaMATRotationEnum(GraphInstance->Rotation), ShiftWidth, ShiftHeight))
	{
		InstaMATInterface->DeallocElementExecution(ExecutionKey);
		UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not set Composition Graph settings for Graph with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/true)));
		return;
	}
	GraphInstance->bIsFormatSettingsDirty = false;

	if (!InstaMATInterface->ExecuteElementExecutionForKey(ExecutionKey, ExecutionFormat > InstaMAT::ElementExecutionFormat::Normalized8, ExecutionFormat, InstaMAT::GetRotationInRadiansForInstaMATRotationEnum(GraphInstance->Rotation), ShiftWidth, ShiftHeight))
	{
		InstaMATInterface->DeallocElementExecution(ExecutionKey);
		UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not execute ElementExecution for Graph with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/true)));
		return;
	}

	const FString TexturePath = FString::Printf(TEXT("%s_Assets/"), *UnrealPackage->GetName());

	// texture output parameters
	for (UInstaMATOutput* const OutputParameter : GraphInstance->OutputParameters)
	{
		InstaMAT::IImageSampler* const Sampler = InstaMATInterface->GetImageSamplerForOutputParameter(ExecutionKey, OutputParameter->Index);
		if (Sampler == nullptr)
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not retrieve Output data for Graph with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/true)));
			continue;
		}

		const FString ObjectName = FInstaMATImporterUtility::EnsureValidObjectName(OutputParameter->OutputName);
		const bool bIsNormalTexture = OutputParameter->OutputName.ToLower().Contains("normal");
		const FString LongName = FPaths::Combine(*TexturePath, *ObjectName);

		UPackage* const SubPackage = CreatePackage(*LongName);
		check(SubPackage != nullptr);

		if (SubPackage == nullptr)
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not create package with name='%s'"), *LongName);
			continue;
		}

		check(OutputParameter->ColorChannelCount <= 4u);

		// convert data
		if (OutputParameter->ColorChannelCount > 4u)
		{
			UE_LOG(LogInstaMAT, Fatal, TEXT("InstaMAT: Color channel count is invalid for Graph Object with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/true)));
			continue;
		}

		const TextureCompressionSettings CompressionSettings = InstaMATTextureUtility::GetTextureCompressionFormat(OutputParameter->OutputName, OutputParameter->ColorChannelCount, GraphInstance->ExecutionFormat);
		uint64 SamplerDataSize = 0u;
		uint8* const SamplerData = Sampler->GetData(&SamplerDataSize);
#if defined (INSTAMAT_ENABLE_CREATE_TEXTURES_BY_MATERIALUTILITIES)
		const TArray<FColor> Samples = InstaMATTextureUtility::CreateColorSamplesFromByteData(TextureWidth, TextureHeight, OutputParameter->ColorChannelCount, SamplerData);

		// create texture 2d Object
		OutputParameter->Output = FMaterialUtilities::CreateTexture(UnrealPackage, OutputParameter->OutputName, FIntPoint(TextureWidth, TextureHeight), Samples, CompressionSettings, TEXTUREGROUP_HierarchicalLOD, RF_Public | RF_Standalone, /*FIXME: bIsSRGB*/false);
#else
		OutputParameter->Output = NewObject<UTexture2D>(SubPackage, *ObjectName, RF_Public | RF_Standalone);
		OutputParameter->Output->AddToRoot();
		InstaMATTextureUtility::FillUTexture2D(OutputParameter->Output, TextureWidth, TextureHeight, OutputParameter->ColorChannelCount, SamplerData, SamplerDataSize, GraphInstance->ExecutionFormat);
#endif
		InstaMATInterface->GetInstaMAT()->DeallocImageSampler(Sampler);

		InstaMAT::IGraphVariable::ColorSpaceType ColorSpace;
		if (InstaMATInterface->GetColorSpaceForOutputParameter(ExecutionKey, OutputParameter->Index, ColorSpace))
		{
			// NOTE: UE only supports SRGB on 8-bits textures. Setting SRGB as true on >8bpp doesn't do anything.
			OutputParameter->Output->SRGB = ExecutionFormat == InstaMAT::ElementExecutionFormat::Normalized8 && ColorSpace == InstaMAT::IGraphVariable::ColorSpaceTypeSRGB && !bIsNormalTexture;
		}

		OutputParameter->Output->MipLoadOptions = ETextureMipLoadOptions::OnlyFirstMip;
		OutputParameter->Output->MipGenSettings = TextureMipGenSettings::TMGS_FromTextureGroup;
		OutputParameter->Output->CompressionSettings = CompressionSettings;
		OutputParameter->Output->DeferCompression = true;
		OutputParameter->Output->PostEditChange();
		OutputParameter->Output->MarkPackageDirty();
		FAssetRegistryModule::AssetCreated(OutputParameter->Output);

		// create UI Brush
		constexpr double kBrushSize = 48.0;
		const FVector2D UIImageSize(kBrushSize, kBrushSize);
		OutputParameter->Brush = MakeShared<FSlateDynamicImageBrush>(OutputParameter->Output, UIImageSize, OutputParameter->Output->GetFName());
	}

	// mesh output parameters
	for (UInstaMATMeshOutput* const OutputParameter : GraphInstance->OutputMeshParameters)
	{
		const FString ObjectName = FInstaMATImporterUtility::EnsureValidObjectName(OutputParameter->OutputName);
		const FString LongName = FPaths::Combine(*TexturePath, *ObjectName);
		UPackage* const SubPackage = CreatePackage(*LongName);
		check(SubPackage != nullptr);

		if (SubPackage == nullptr)
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not create package with name='%s'"), *LongName);
			continue;
		}

		OutputParameter->Output = NewObject<UStaticMesh>(SubPackage, *ObjectName, RF_Public | RF_Standalone);
		OutputParameter->Output->AddToRoot();

		const int OldSourceModelNum = OutputParameter->Output->GetSourceModels().Num();
		OutputParameter->Output->SetNumSourceModels(OldSourceModelNum + 1);

		FStaticMeshSourceModel& SourceModel = OutputParameter->Output->GetSourceModel(OldSourceModelNum);
		SourceModel.CreateMeshDescription();
		check(SourceModel.GetCachedMeshDescription() != nullptr);

		FMeshDescription& NewMeshDescription = *SourceModel.GetCachedMeshDescription();
		FStaticMeshAttributes(NewMeshDescription).Register();

		if (!GraphInstance->bIsMaterialGraph && GraphInstance->MaterialInstance != nullptr)
		{
			FStaticMaterial NewStaticMaterial(GraphInstance->MaterialInstance);
			OutputParameter->Output->GetStaticMaterials().Add(NewStaticMaterial);
		}

		const InstaMAT::IGraphMesh* Mesh = nullptr;
		if (!InstaMATInterface->GetMeshDataForOutputParameter(ExecutionKey, OutputParameter->Index, &Mesh))
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not retrieve mesh Output data for Graph with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/true)));
			continue;
		}

		check(Mesh != nullptr);

		if (Mesh == nullptr)
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not retrieve mesh Output data for Graph with name='%s'"), ANSI_TO_TCHAR(GraphObject->GetName(/*friendlyName:*/true)));
			continue;
		}

		if (!InstaMATInterface->ConvertGraphMeshToMeshDescription(*Mesh, NewMeshDescription))
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Could not convert InstaMAT mesh to static mesh"));
			continue;
		}

		// save to bulk
		if (SourceModel.IsMeshDescriptionValid())
		{
			SourceModel.CommitMeshDescription(/*bUseHashAsGuid*/ true);
		}

		// set build settings or normals will get recalculated
		SourceModel.BuildSettings.bRecomputeNormals = false;
		SourceModel.BuildSettings.bRecomputeTangents = false;
		SourceModel.BuildSettings.bBuildReversedIndexBuffer = false;
		SourceModel.BuildSettings.bUseMikkTSpace = true;

		// Make sure at least one material slot is present automatically so users can assign custom materials to it without having to manually create a material slot.
		TArray<FStaticMaterial>& StaticMaterials = OutputParameter->Output->GetStaticMaterials();
		if (StaticMaterials.IsEmpty())
		{
			StaticMaterials.Add(FStaticMaterial());
		}

		OutputParameter->Output->ImportVersion = EImportStaticMeshVersion::LastVersion;
		OutputParameter->Output->Build();
		OutputParameter->Output->PostEditChange();
		OutputParameter->Output->MarkPackageDirty();
		FAssetRegistryModule::AssetCreated(OutputParameter->Output);

		// create brush
		OutputParameter->Brush = MakeShared<FSlateBrush>();
		// OutputParameter->Brush->SetResourceObject(OutputParameter->Output);
	}
	
	// scene output parameters
	const FString ScenePackagePath = FString::Printf(TEXT("%s_Scene/"), *UnrealPackage->GetName());

	for (UInstaMATGraphSceneOutput* const OutputParameter : GraphInstance->OutputSceneParameters)
	{
		FInstaMATImporterUtility::ImportOutputGraphScene(InstaMATModule, GraphInstance, OutputParameter, ScenePackagePath);
	}

	// Enable updating
	GraphInstance->SetDirty(/*bIsDirty:*/false, /*bNextPropertyEventIgnore:*/false);
}

void FInstaMATImporterUtility::ConnectTexturesToMaterialByProperty(const TMap<EMaterialProperty, UTexture2D*>& PropertyToTexture, UMaterialInstanceConstant* const Material, const float DisplacementHeight, const bool bIsBaseColorGrayscale)
{
	/// The fnCheckAndCreateSwitchParameter checks whether the property exists and then creates the switch parameter
	const auto fnCheckAndCreateSwitchParameter = [&PropertyToTexture, Material, /*copy:*/ bIsBaseColorGrayscale](const EMaterialProperty Property, const FName& Name, const FMaterialParameterInfo& ParameterInfo, bool bIsEnabled = true) -> bool
	{
		if (!PropertyToTexture.Contains(Property))
			return false;

		FMaterialParameterInfo Info;
		Info.Association = EMaterialParameterAssociation::GlobalParameter;
		Info.Index = INDEX_NONE;
		Info.Name = Name;

		if (bIsEnabled)
		{
			Material->SetStaticSwitchParameterValueEditorOnly(Info, bIsEnabled);
		}
		Material->SetTextureParameterValueEditorOnly(ParameterInfo, PropertyToTexture[Property]);

		if (bIsBaseColorGrayscale && Property == EMaterialProperty::MP_BaseColor)
		{
			FMaterialParameterInfo BaseColorParameter;
			BaseColorParameter.Association = EMaterialParameterAssociation::GlobalParameter;
			BaseColorParameter.Index = INDEX_NONE;
			BaseColorParameter.Name = TEXT("UseGrayscaleBaseColor");

			Material->SetStaticSwitchParameterValueEditorOnly(BaseColorParameter, true);
		}

		return true;
	};

	const bool bIsNaniteDisplacementEnabled = CVarEnableNaniteDisplacement.GetValueOnAnyThread();

	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_BaseColor, TEXT("UseBaseColor"), TEXT("BaseColorTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_Metallic, TEXT("UseMetallic"), TEXT("MetallicTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_Specular, TEXT("UseSpecular"), TEXT("SpecularTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_Roughness, TEXT("UseRoughness"), TEXT("RoughnessTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_Normal, TEXT("UseNormal"), TEXT("NormalTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_Opacity, TEXT("UseOpacity"), TEXT("OpacityTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_EmissiveColor, TEXT("UseEmissiveColor"), TEXT("EmissiveColorTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_OpacityMask, TEXT("UseOpacityMask"), TEXT("OpacityMaskTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_AmbientOcclusion, TEXT("UseAmbientOcclusion"), TEXT("AmbientOcclusionTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_Anisotropy, TEXT("UseAnisotropy"), TEXT("AnisotropyTexture"));
	fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_Displacement, TEXT("UseNaniteDisplacement"), TEXT("HeightTexture"), bIsNaniteDisplacementEnabled);

	UInstaMATSettings* const DefaultObject = UInstaMATSettings::StaticClass()->GetDefaultObject<UInstaMATSettings>();

	// Enable Subsurfacec rendering if avaialable
	if (fnCheckAndCreateSwitchParameter(EMaterialProperty::MP_SubsurfaceColor, TEXT("UseSubsurfaceColor"), TEXT("SubsurfaceColorTexture")))
	{
		Material->BasePropertyOverrides.bOverride_ShadingModel = true;

		if (DefaultObject->bIsShadingModelSubsurfaceEnabled)
		{
			Material->BasePropertyOverrides.ShadingModel = EMaterialShadingModel::MSM_Subsurface;
		}
		else
		{
			Material->BasePropertyOverrides.ShadingModel = EMaterialShadingModel::MSM_DefaultLit;
		}
	}

	// NOTE: MP_WorldDisplacement is deprecated since UE 5.0
	if (PropertyToTexture.Contains(EMaterialProperty::MP_Displacement))
	{
		FMaterialParameterInfo Info;
		{
			Info.Association = EMaterialParameterAssociation::GlobalParameter;
			Info.Index = INDEX_NONE;
			Info.Name = FName(TEXT("UseParallaxOcclusionMapping"));
		}
		Material->SetStaticSwitchParameterValueEditorOnly(Info, !bIsNaniteDisplacementEnabled);

		const float kMaximumDisplacement = 0.08f;

		FScalarParameterValue Parameter;
		Parameter.ParameterInfo = FName(TEXT("ParallaxRatio"));
		Parameter.ParameterValue = FMath::Min<float>(DisplacementHeight / /*ToMeters:*/ 100.0f, kMaximumDisplacement);
		Material->ScalarParameterValues.Add(Parameter);
		Material->SetTextureParameterValueEditorOnly(TEXT("HeightTexture"), PropertyToTexture[EMaterialProperty::MP_Displacement]);
	}

	// set blend mode if necessary 
	if (PropertyToTexture.Contains(EMaterialProperty::MP_Opacity) || PropertyToTexture.Contains(EMaterialProperty::MP_OpacityMask))
	{
		Material->BasePropertyOverrides.bOverride_BlendMode = true;
		Material->BasePropertyOverrides.BlendMode = PropertyToTexture.Contains(EMaterialProperty::MP_Opacity) ? EBlendMode::BLEND_Translucent : EBlendMode::BLEND_Masked;
	}

	// NOTE: Nanite displacement is set through an override
	Material->BasePropertyOverrides.bOverride_DisplacementScaling = true;
	Material->BasePropertyOverrides.DisplacementScaling.Magnitude = DisplacementHeight;
}

void FInstaMATImporterUtility::ConnectTexturesToMaterial(const TArray<UTexture2D*>& Textures, UMaterialInstanceConstant* const Material, const FInstaMATMaterialParameters& MaterialSettings)
{
	check(Material != nullptr);

	TMap<EMaterialProperty, UTexture2D*> PropertyToTexture;

	// assign textures to material properties by name
	for (UTexture2D* const Texture : Textures)
	{
		FString TextureName;
		Texture->GetName(TextureName);
		TextureName.ReplaceInline(TEXT("_"), TEXT(" "));
		TextureName.ToLowerInline();

		EMaterialProperty Property = EMaterialProperty::MP_MAX;
		for (const auto& [Key, Value] : kTextureNameToMaterialProperty)
		{
			if (TextureName.Contains(Key, ESearchCase::IgnoreCase))
			{
				Property = Value;
				break;
			}
		}

		if (Property == EMaterialProperty::MP_MAX)
			continue;

		if (PropertyToTexture.Contains(Property))
		{
			const FString PropertyName = UEnum::GetValueAsString<EMaterialProperty>(Property);
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Multiple possible assignments for property='%s'"), *PropertyName);
		}

		PropertyToTexture.Emplace(Property, Texture);
	}

	FInstaMATImporterUtility::ConnectTexturesToMaterialByProperty(PropertyToTexture, Material, MaterialSettings.DisplacementHeight, MaterialSettings.bIsBaseColorGrayscale);

	if (MaterialSettings.bHasPhysicalSize)
	{
		FScalarParameterValue Parameter;
		Parameter.ParameterInfo = FName(TEXT("PhysicalSize U"));
		Parameter.ParameterValue = MaterialSettings.Width;
		Material->ScalarParameterValues.Add(Parameter);

		Parameter = FScalarParameterValue();
		Parameter.ParameterInfo = FName(TEXT("PhysicalSize V"));
		Parameter.ParameterValue = MaterialSettings.Height;
		Material->ScalarParameterValues.Add(Parameter);
	}

	// force initializing the static permutations according to the switches we have set
	Material->InitStaticPermutation();
	Material->PostEditChange();
}

void FInstaMATImporterUtility::ConnectTexturesToMaterial(const TMap<InstaMAT::GraphMaterialTexture::Type, UTexture2D*>& Textures, UMaterialInstanceConstant* const Material, const InstaMAT::GraphMaterialProperties& Properties)
{
	check(Material != nullptr);
	
	static const TMap<InstaMAT::GraphMaterialTexture::Type, EMaterialProperty> kPropertyConnection = {
		{ InstaMAT::GraphMaterialTexture::TypeColor,					EMaterialProperty::MP_BaseColor },
		{ InstaMAT::GraphMaterialTexture::TypeNormalMapTangentSpace,	EMaterialProperty::MP_Normal },
		{ InstaMAT::GraphMaterialTexture::TypeNormalMapObjectSpace,		EMaterialProperty::MP_Normal },
		{ InstaMAT::GraphMaterialTexture::TypeOpacity,					EMaterialProperty::MP_Opacity },
		{ InstaMAT::GraphMaterialTexture::TypeAmbientOcclusion,			EMaterialProperty::MP_AmbientOcclusion },
		{ InstaMAT::GraphMaterialTexture::TypeRoughness,				EMaterialProperty::MP_Roughness },
		{ InstaMAT::GraphMaterialTexture::TypeSpecular,					EMaterialProperty::MP_Specular },
		{ InstaMAT::GraphMaterialTexture::TypeMetalness,				EMaterialProperty::MP_Metallic },
		{ InstaMAT::GraphMaterialTexture::TypeEmissive,					EMaterialProperty::MP_EmissiveColor },
		{ InstaMAT::GraphMaterialTexture::TypeSubsurfaceColor,			EMaterialProperty::MP_SubsurfaceColor },
		{ InstaMAT::GraphMaterialTexture::TypeHeight,					EMaterialProperty::MP_Displacement }
	};

	TMap <EMaterialProperty, UTexture2D*> PropertyToTexture;

	for (const auto& [Type, Texture] : Textures)
	{
		if (Texture == nullptr)
			continue;

		if (Type == InstaMAT::GraphMaterialTexture::TypeOpacity && Properties.IsOpacityMasked)
		{
			PropertyToTexture.Emplace(EMaterialProperty::MP_OpacityMask, Texture);
			continue;
		}

		if (!kPropertyConnection.Contains(Type))
		{
			UE_LOG(LogInstaMAT, Warning, TEXT("InstaMAT: Material type not supported in Unreal Engine."));
			continue;
		}

		PropertyToTexture.Emplace(kPropertyConnection[Type], Texture);
	}

	FInstaMATImporterUtility::ConnectTexturesToMaterialByProperty(PropertyToTexture, Material, Properties.DisplacementMaximum, /*bIsBaseColorGrayscale:*/ false);
	FVectorParameterValue VectorParameter;
	VectorParameter.ParameterInfo = FName(TEXT("BaseColorConst"));
	VectorParameter.ParameterValue = FLinearColor(Properties.BaseColor.R, Properties.BaseColor.G, Properties.BaseColor.B, 1.0f);
	Material->VectorParameterValues.Add(VectorParameter);
	
	Material->ScalarParameterValues.Add(FScalarParameterValue(FName(TEXT("MetallicConst")), Properties.Metalness));
	Material->ScalarParameterValues.Add(FScalarParameterValue(FName(TEXT("RoughnessConst")), Properties.Roughness));
	Material->ScalarParameterValues.Add(FScalarParameterValue(FName(TEXT("OpacityConst")), Properties.Opacity));
	Material->ScalarParameterValues.Add(FScalarParameterValue(FName(TEXT("EmissiveScale")), Properties.EmissiveIntensity));

	Material->VectorParameterValues.Add(FVectorParameterValue(FName(TEXT("BaseColorConst")), FLinearColor(Properties.BaseColor.R, Properties.BaseColor.G, Properties.BaseColor.B, 1.0f)));

	Material->InitStaticPermutation();
	Material->PostEditChange();
}

void FInstaMATImporterUtility::GetResolutionValues(uint32& OutWidth, uint32& OutHeight, int32& OutShiftWidth, int32& OutShiftHeight)
{
	if (OutWidth <= kInstaMATDownSampleResolutionThreshold)
	{
		OutWidth *= 2;
		OutShiftWidth = -1;
	}

	if (OutHeight <= kInstaMATDownSampleResolutionThreshold)
	{
		OutHeight *= 2;
		OutShiftHeight = -1;
	}
}

